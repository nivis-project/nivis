package gen

import (
	"fmt"
	"strings"
)

// reservedFormals are the constructor's own lambda parameters: a provider
// attribute or block sharing one of these names would duplicate a formal (invalid
// Nix) or shadow a parameter (corrupting the instance name or the override merge).
// Such a colliding attribute is accepted under an alias (formal) and emitted into
// config under its real key. See gen-reserved-names / nixform2-56tm.
var reservedFormals = map[string]bool{
	"name":      true, // the Nivis resource instance name (threaded to mkResource)
	"overrides": true, // the override-merge seam
	"nivis":     true, // the library argument
}

// formalFor returns the lambda formal to use for a real attribute/block name: the
// name itself, or a safe `cfg_<name>` alias when the name is reserved. The real
// key always stays the attribute's true name in config.
func formalFor(name string) string {
	if reservedFormals[name] {
		return "cfg_" + name
	}
	return name
}

// Emit renders a Nix constructor module for one resource type. The module is a
// function of the nivis library plus the user's inputs:
//
//	{ nivis }:
//	{ name, <required>..., <optional> ? null..., overrides ? {} }:
//	let
//	  _required = <throw if a required arg is null>;
//	  config = <built from inputs, computed-only attrs omitted>;
//	in nivis.mkResource ({ provider; type; name; config; } // overrides)
//
// Inputs are the required + optional attributes; computed-only attributes are
// outputs (referenced via the resource's refAttr), never inputs. `overrides` is
// merged last (the Pulumi overlay lesson: generated code is usable, not final).
// A provider attribute whose name collides with a reserved formal (name,
// overrides, nivis) is accepted under a `cfg_<name>` alias and still emitted into
// config under its real key, so the generated file is always valid Nix.
// Output is deterministic (attributes are pre-sorted in the model).
func Emit(provider string, r Resource) string {
	var inputs []Attr
	for _, a := range r.Attrs {
		if a.IsInput() {
			inputs = append(inputs, a)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by tn-gen for %s.%s — do not edit by hand.\n", provider, r.Type)
	fmt.Fprintf(&b, "# Computed outputs (read via the resource's refAttr): %s\n", computedNames(r))
	// Document any reserved-name aliasing so the file stays a readable reference:
	// the provider attribute keeps its real key in config but is taken under an alias.
	for _, a := range inputs {
		if reservedFormals[a.Name] {
			fmt.Fprintf(&b, "# Note: provider attribute %q clashes with a reserved argument; pass it as %q (it lands in config as %q).\n",
				a.Name, formalFor(a.Name), a.Name)
		}
	}
	for _, blk := range r.Blocks {
		if reservedFormals[blk.Name] {
			fmt.Fprintf(&b, "# Note: provider block %q clashes with a reserved argument; pass it as %q (it lands in config as %q).\n",
				blk.Name, formalFor(blk.Name), blk.Name)
		}
	}
	// Nested blocks are documented here so the generated file doubles as the
	// per-provider argument reference (A5): each names its nesting + inner attrs.
	for _, blk := range r.Blocks {
		fmt.Fprintf(&b, "# Block %q (%s-nested): %s. Shape: %s\n",
			blk.Name, blk.Nesting, blockAttrNames(blk), blockShapeHint(blk))
	}
	b.WriteString("{ nivis }:\n")

	// argument set. Required args also default to null so our own throw (which
	// names provider.type and the argument) fires with a friendly message,
	// rather than Nix's generic "called without required argument" arglist error.
	// Reserved-name collisions are taken under a cfg_<name> alias (formalFor).
	b.WriteString("{ name")
	for _, a := range inputs {
		fmt.Fprintf(&b, ", %s ? null", formalFor(a.Name))
	}
	// Each nested block is an input defaulting to the empty shape for its nesting,
	// so the correct shape ([] for list/set, null attrset for single, {} for map)
	// is the obvious one and list-vs-single cannot be guessed wrong.
	for _, blk := range r.Blocks {
		fmt.Fprintf(&b, ", %s ? %s", formalFor(blk.Name), blockDefault(blk))
	}
	b.WriteString(", overrides ? {} }:\n")

	b.WriteString("let\n")
	// required-presence checks. The binding reads the (possibly aliased) formal;
	// the error message keeps the provider's real attribute name. The let binding
	// name is derived from the formal, so it too cannot collide.
	for _, a := range inputs {
		if a.Required {
			f := formalFor(a.Name)
			fmt.Fprintf(&b,
				"  _%s = if %s == null then throw \"%s.%s: required argument '%s' is missing\" else %s;\n",
				f, f, provider, r.Type, a.Name, f)
		}
	}
	// config: include required (checked) always under the REAL key; optional only
	// when non-null, again under the real key, reading from the (aliased) formal.
	b.WriteString("  config =\n")
	b.WriteString("    {")
	for _, a := range inputs {
		if a.Required {
			fmt.Fprintf(&b, " %s = _%s;", a.Name, formalFor(a.Name))
		}
	}
	b.WriteString(" }\n")
	for _, a := range inputs {
		if !a.Required {
			f := formalFor(a.Name)
			fmt.Fprintf(&b,
				"    // (if %s == null then {} else { %s = %s; })\n", f, a.Name, f)
		}
	}
	// blocks: include when the user supplied a non-empty value (single: non-null;
	// list/set/map: the empty default already serializes harmlessly, but we still
	// only include a single block when set). Real key, aliased formal.
	for _, blk := range r.Blocks {
		f := formalFor(blk.Name)
		if blk.Nesting == NestSingle {
			fmt.Fprintf(&b,
				"    // (if %s == null then {} else { %s = %s; })\n", f, blk.Name, f)
		} else {
			fmt.Fprintf(&b, "    // { %s = %s; }\n", blk.Name, f)
		}
	}
	b.WriteString("    ;\n")
	b.WriteString("in\n")
	fmt.Fprintf(&b,
		"nivis.mkResource ({ provider = %q; type = %q; inherit name config; } // overrides)\n",
		provider, r.Type)

	return b.String()
}

// blockDefault is the empty default value for a block argument, matching its
// nesting: a list/set is [], a single block is null (one attrset), a map is {}.
func blockDefault(b Block) string {
	switch b.Nesting {
	case NestList, NestSet:
		return "[ ]"
	case NestMap:
		return "{ }"
	default: // single
		return "null"
	}
}

// blockShapeHint is a one-line hint of how to write the block, by nesting.
func blockShapeHint(b Block) string {
	switch b.Nesting {
	case NestList, NestSet:
		return "[ { ... } ]"
	case NestMap:
		return "{ <key> = { ... }; }"
	default: // single
		return "{ ... }"
	}
}

// blockAttrNames lists a block's inner input attribute names (for the doc line).
func blockAttrNames(b Block) string {
	var names []string
	for _, a := range b.Attrs {
		if a.IsInput() {
			names = append(names, a.Name)
		}
	}
	for _, sub := range b.Blocks {
		names = append(names, sub.Name+" (block)")
	}
	if len(names) == 0 {
		return "(no input attributes)"
	}
	return strings.Join(names, ", ")
}

func computedNames(r Resource) string {
	var names []string
	for _, a := range r.Attrs {
		if a.Computed && !a.IsInput() {
			names = append(names, a.Name)
		}
	}
	if len(names) == 0 {
		return "(none)"
	}
	return strings.Join(names, ", ")
}
