package gen

import (
	"fmt"
	"strings"
)

// Emit renders a Nix constructor module for one resource type. The module is a
// function of the nivis library plus the user's inputs:
//
//	{ nivis }:
//	{ name, <required>..., <optional> ? null..., overrides ? {} }:
//	let
//	  _required = <throw if a required arg is null>;
//	  config = <built from inputs, computed-only attrs omitted>;
//	in nivis.mkResource ({ provider; type; name; config; } // overrides)
//
// Inputs are the required + optional attributes; computed-only attributes are
// outputs (referenced via the resource's refAttr), never inputs. `overrides` is
// merged last (the Pulumi overlay lesson: generated code is usable, not final).
// Output is deterministic (attributes are pre-sorted in the model).
func Emit(provider string, r Resource) string {
	var inputs []Attr
	for _, a := range r.Attrs {
		if a.IsInput() {
			inputs = append(inputs, a)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by tn-gen for %s.%s — do not edit by hand.\n", provider, r.Type)
	fmt.Fprintf(&b, "# Computed outputs (read via the resource's refAttr): %s\n", computedNames(r))
	// Nested blocks are documented here so the generated file doubles as the
	// per-provider argument reference (A5): each names its nesting + inner attrs.
	for _, blk := range r.Blocks {
		fmt.Fprintf(&b, "# Block %q (%s-nested): %s. Shape: %s\n",
			blk.Name, blk.Nesting, blockAttrNames(blk), blockShapeHint(blk))
	}
	b.WriteString("{ nivis }:\n")

	// argument set. Required args also default to null so our own throw (which
	// names provider.type and the argument) fires with a friendly message,
	// rather than Nix's generic "called without required argument" arglist error.
	b.WriteString("{ name")
	for _, a := range inputs {
		fmt.Fprintf(&b, ", %s ? null", a.Name)
	}
	// Each nested block is an input defaulting to the empty shape for its nesting,
	// so the correct shape ([] for list/set, null attrset for single, {} for map)
	// is the obvious one and list-vs-single cannot be guessed wrong.
	for _, blk := range r.Blocks {
		fmt.Fprintf(&b, ", %s ? %s", blk.Name, blockDefault(blk))
	}
	b.WriteString(", overrides ? {} }:\n")

	b.WriteString("let\n")
	// required-presence checks
	for _, a := range inputs {
		if a.Required {
			fmt.Fprintf(&b,
				"  _%s = if %s == null then throw \"%s.%s: required argument '%s' is missing\" else %s;\n",
				a.Name, a.Name, provider, r.Type, a.Name, a.Name)
		}
	}
	// config: include required (checked) always; optional only when non-null.
	b.WriteString("  config =\n")
	b.WriteString("    {")
	for _, a := range inputs {
		if a.Required {
			fmt.Fprintf(&b, " %s = _%s;", a.Name, a.Name)
		}
	}
	b.WriteString(" }\n")
	for _, a := range inputs {
		if !a.Required {
			fmt.Fprintf(&b,
				"    // (if %s == null then {} else { %s = %s; })\n", a.Name, a.Name, a.Name)
		}
	}
	// blocks: include when the user supplied a non-empty value (single: non-null;
	// list/set/map: the empty default already serializes harmlessly, but we still
	// only include a single block when set).
	for _, blk := range r.Blocks {
		if blk.Nesting == NestSingle {
			fmt.Fprintf(&b,
				"    // (if %s == null then {} else { %s = %s; })\n", blk.Name, blk.Name, blk.Name)
		} else {
			fmt.Fprintf(&b, "    // { %s = %s; }\n", blk.Name, blk.Name)
		}
	}
	b.WriteString("    ;\n")
	b.WriteString("in\n")
	fmt.Fprintf(&b,
		"nivis.mkResource ({ provider = %q; type = %q; inherit name config; } // overrides)\n",
		provider, r.Type)

	return b.String()
}

// blockDefault is the empty default value for a block argument, matching its
// nesting: a list/set is [], a single block is null (one attrset), a map is {}.
func blockDefault(b Block) string {
	switch b.Nesting {
	case NestList, NestSet:
		return "[ ]"
	case NestMap:
		return "{ }"
	default: // single
		return "null"
	}
}

// blockShapeHint is a one-line hint of how to write the block, by nesting.
func blockShapeHint(b Block) string {
	switch b.Nesting {
	case NestList, NestSet:
		return "[ { ... } ]"
	case NestMap:
		return "{ <key> = { ... }; }"
	default: // single
		return "{ ... }"
	}
}

// blockAttrNames lists a block's inner input attribute names (for the doc line).
func blockAttrNames(b Block) string {
	var names []string
	for _, a := range b.Attrs {
		if a.IsInput() {
			names = append(names, a.Name)
		}
	}
	for _, sub := range b.Blocks {
		names = append(names, sub.Name+" (block)")
	}
	if len(names) == 0 {
		return "(no input attributes)"
	}
	return strings.Join(names, ", ")
}

func computedNames(r Resource) string {
	var names []string
	for _, a := range r.Attrs {
		if a.Computed && !a.IsInput() {
			names = append(names, a.Name)
		}
	}
	if len(names) == 0 {
		return "(none)"
	}
	return strings.Join(names, ", ")
}
